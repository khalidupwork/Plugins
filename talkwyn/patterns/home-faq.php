<div class="wp-block-group tw-faq"><!-- wp:details -->
<details class="wp-block-details"><summary>Is Talkwyn really free?</summary><!-- wp:paragraph -->
<p>Yes. The free plan includes site scanning, multilingual answers, lead capture, and chat history. You only pay if you want <a href="/pricing/">Pro features</a> like advanced search, analytics, and white-label.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Do I need to pay for AI?</summary><!-- wp:paragraph -->
<p>Not to get started. Groq, Google Gemini, OpenRouter, and Cloudflare offer <a href="/docs/ai-providers/">free tiers</a> that are enough for many small business sites. Free limits are set by each provider and can change, which is why Talkwyn lets you add more than one.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Which languages does it support?</summary><!-- wp:paragraph -->
<p>Talkwyn replies in <a href="/multilingual-chatbot/">the language your visitor writes in</a>. That includes Arabic, Urdu, Roman Urdu, Hindi, English, Spanish, French, German, Turkish, Chinese, Japanese, and many more, depending on the AI model you choose.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will it make things up?</summary><!-- wp:paragraph -->
<p>Talkwyn is instructed to answer business questions only from your website content. If the answer isn't there, it says so and offers to connect the visitor with your team.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Does it work with Elementor and WooCommerce?</summary><!-- wp:paragraph -->
<p>Yes. Talkwyn reads <a href="/wordpress-ai-chatbot/">Elementor page content and WooCommerce product details</a> such as price, stock status, and attributes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Will it slow down my site?</summary><!-- wp:paragraph -->
<p>The chat script is small, loads after your page, and talks to your server only when someone sends a message.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Where are my chats and leads stored?</summary><!-- wp:paragraph -->
<p>In your own WordPress database. You can export leads as CSV and <a href="/privacy/">set logs to delete automatically</a>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I use it on client sites?</summary><!-- wp:paragraph -->
<p>Yes. <a href="/agencies/">The Agency plan</a> covers unlimited sites and lets you remove our branding.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

